/**
 * 推播的內容格式（設計架構書 §9.1、§13.2 第 9 條）
 *
 * 這個物件會被 JSON 序列化送出去，由 `public/sw.js` 的 `push` 事件收下。
 * **兩邊的欄位名稱必須一致**，而它們分屬伺服器與瀏覽器兩個執行環境、
 * 沒有共用型別——所以改欄位時要同時改那支檔案，這裡是唯一的提醒。
 *
 * §13.2 第 9 條：**推播文案使用規則模板，不使用 AI 生成。**
 * 週末早晨那則的模板屬於 §9.1，還沒實作；這裡先只有測試通知，
 * 它的存在理由是驗證整條路徑（訂閱 → 伺服器 → 推播服務 → 裝置）。
 */
export interface PushPayload {
  title: string;
  body: string;
  /** 點下通知時要開的頁面。§9.1 的推播會指向 /today（ADR-0011 帶連結） */
  url: string;
  /**
   * 同一個 tag 的通知會互相取代而不是疊加。
   * 週末只有兩則推播（§9.1、§9.2），但重試或重新整理不該讓通知中心長出一排。
   */
  tag: string;
}

/**
 * 測試通知。**刻意寫得像一則真的建議**——只說「這是測試」的話，
 * 驗不掉「文字長度在鎖定畫面上會不會被截掉」這種只有真機才看得出來的事。
 */
export const TEST_NOTIFICATION: PushPayload = {
  title: "KidGo 推播測試",
  body: "收到這則就代表這台裝置的推播是通的。週末早晨那則還沒排程。",
  url: "/today",
  tag: "kidgo-test",
};
