/**
 * 「看看這是哪」的地圖連結（ADR-0011 修訂四）
 *
 * ADR-0011：**連結開的是地圖服務的地點頁（照片與評論），不是導航。**
 * 現在的替代路徑是「記住地名 → 切換 App → 打字 → 搜尋 → 找到正確那一筆」，
 * 四五步。§9.1 說「不得要求開啟 App 才能理解」禁止的是開**我們的** App；
 * 跳去看照片是使用者的合理需求，不是設計失敗。
 *
 * ## 為什麼是「名稱 + 座標」而不是其中之一
 *
 * - **只給座標**：位置一定對，但多半只掉一個大頭針，**看不到照片**——
 *   那正是這個連結存在的唯一理由，等於沒解決問題
 * - **只給名稱**：通常會開到地點頁，但同名地點會開錯。
 *   資料庫裡就有四組：福星公園、新興公園、公館公園、中興公園各兩個
 *
 * 所以兩個都給：名稱負責找到地點頁，座標負責保證是**這一個**。
 *
 * ## 為什麼不自己推算行政區
 *
 * 曾經考慮過「板橋 華江八號公園」這種帶行政區的搜尋字串。可行，但要從座標
 * 反推行政區——用 townships.ts 的中心點找最近的，2026-08-31 以 502 筆
 * 地址裡自己寫了行政區的資料實測：**完全命中只有 78.5%**，另有 15.9%
 * 落在相鄰區（士林 ↔ 北投 這類），5.6% 甚至跨縣市。
 *
 * 中心點距離法在相鄰區之間本來就分不清楚——行政區是不規則多邊形不是圓形。
 *
 * 更重要的是它違反 §6.2 的原則「只記錄地圖服務與現有懶人包查不到的東西」：
 * 行政區是 Google 知道得一清二楚的東西，我們卻要用五分之一會錯的準確度去猜，
 * 再把猜測餵給 Google 搜尋。座標我們是精確的，那才是該拿出來用的東西。
 *
 * ## 網址形式的已知風險
 *
 * `/maps/search/<查詢>/@<lat>,<lng>,<zoom>z` 是 Google Maps 自己在用的正規
 * 網址（搜尋完從網址列複製下來就是這個形狀），非常穩定，但**它不在官方
 * 「Maps URLs」文件列出的形式裡**——文件只列 `?api=1&query=`。
 * 若哪天失效，換成官方形式是改這個函式的一行，代價僅是同名地點會開錯。
 */

import type { Place } from "@/lib/db/schema";

/** 地點層級的縮放。再遠會看不出是哪裡，再近會失去周邊參考。 */
const ZOOM = 17;

/** 座標小數位。6 位約 0.1 公尺，遠超過需要，再多只是讓網址變長。 */
const PRECISION = 6;

export function mapsUrl(place: Pick<Place, "name" | "lat" | "lng">): string {
  // 名稱走的是路徑片段，所以斜線、井號一類必須編碼，否則會被讀成路徑結構。
  const query = encodeURIComponent(place.name);
  const lat = place.lat.toFixed(PRECISION);
  const lng = place.lng.toFixed(PRECISION);
  return `https://www.google.com/maps/search/${query}/@${lat},${lng},${ZOOM}z`;
}
